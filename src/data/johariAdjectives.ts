/**
 * Helper to get an adjective by ID or Name
 */
export function getJohariAdjective(query: string): JohariAdjective | undefined {
  const normalized = query.toLowerCase().trim();
  return JOHARI_ADJECTIVES.find(
    (item) => item.id.toLowerCase() === normalized || item.name.toLowerCase() === normalized
  );
}
